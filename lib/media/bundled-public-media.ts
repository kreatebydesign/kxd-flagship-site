const bundledRelative = new Set<string>(BUNDLED_PUBLIC_MEDIA_PATHS);
const bundledByBasename = new Map<string, string>();
for (const rel of BUNDLED_PUBLIC_MEDIA_PATHS) {
  const base = rel.split("/").pop() || rel;
  if (!bundledByBasename.has(base)) bundledByBasename.set(base, rel);
}

export function bundledPublicMediaSrc(filename: string): string | null {
  const trimmed = filename.trim().replace(/^\/+/, "");
  if (!trimmed) return null;
  if (bundledRelative.has(trimmed)) return `/media/${trimmed}`;
  const mapped = bundledByBasename.get(trimmed);
  return mapped ? `/media/${mapped}` : null;
}
